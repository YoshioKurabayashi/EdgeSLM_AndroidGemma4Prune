def build_challenge() -> list[dict]:
    rows, count = [], collections.Counter()

    def add(cat: str, utt: str, act: str, extra: dict | None = None) -> None:
        rows.append({"id": f"c3_{cat}_{count[cat]:03d}", "category": cat, "category_note": NOTES[cat], "utterance": utt, "history": [],
                     "state": {"motion": "stopped", "permission": "allowed"}, "action": ACT[act], "argmode": None,
                     "trainable": False, "purpose": "challenge_eval", "author": "claude", **(extra or {})})
        count[cat] += 1

    for group, items in (("seen", H_SEEN), ("new_seen", H_NEW_SEEN), ("unseen", H_UNSEEN)):
        for name, utts in items:
            if len(utts) != 2:
                raise SystemExit(f"H {name}: 2 文で 1 機能（{len(utts)} 文）")
            for u in utts:
                add("H", u, "unk", {"os_function": name, "os_group": group, "os_function_in_train": group == "seen"})
    for cls, utts in K3.items():
        for u in utts:
            add("K", u, cls)
    for cls, utts in N3.items():
        for u in utts:
            add("N", u, cls)
    for u in F3:
        add("F", u, "chat")
    for kind, utts in G3.items():
        for u in utts:
            add("G", u, "unk", {"g_kind": kind})
    if USER_ROWS.exists():           # 任意: 利用者が足した行（発話<TAB>正解）。正解は 機能なし・不明・雑談・hvac・media・nav・status・manual・poi・minfo・cam
        for line in USER_ROWS.read_text(encoding="utf-8-sig").splitlines():
            if not line.strip() or line.startswith("#"):
                continue
            parts = [x.strip() for x in line.split("\t")]
            if len(parts) < 2 or parts[1] not in USER_LABELS:
                raise SystemExit(f"{USER_ROWS.name}: 読めない行「{line}」（発話<TAB>正解。正解は {'・'.join(USER_LABELS)}）")
            cat, act = USER_LABELS[parts[1]]
            add(cat, parts[0], act, {"author": "user", **({"os_function": "user", "os_group": "user", "os_function_in_train": False} if cat == "H" else {}),
                                     **({"g_kind": "利用者"} if cat == "G" else {})})
    return rows


def build_bert_add() -> list[dict]:
    rows = []
    for name, utts in OS_BERT:
        if len(utts) != 3:
            raise SystemExit(f"OS_BERT {name}: 3 文で 1 単位（{len(utts)} 文）")
        unit = f"bert_os_{name}"
        for k, u in enumerate(utts):
            rows.append({"id": f"{unit}:{k}", "group": unit, "split_unit": unit, "split": "train", "utterance": u, "history": [],
                         "state": {"motion": "stopped", "permission": "allowed"}, "last_tool": None, "route": "UNKNOWN", "category": None,
                         "effect": None, "tool": None, "action": "UNKNOWN", "argmode": None, "difficulty": "hard", "confusable": None,
                         "note": "機能にない依頼（BERT の学習だけに使う）", "trainable": False, "purpose": "rejection_eval",
                         "added": "bert_add_v2", "add_type": "OS", "os_function": name})
    return rows


def main() -> None:
    ch3, add2 = build_challenge(), build_bert_add()
    train = read_jsonl(TR2 / "utterances.jsonl")
    add1 = read_jsonl(BERT_ADD1 / "added.jsonl")
    ch1, ch2 = read_jsonl(CH1), read_jsonl(CH2 / "utterances.jsonl")
    problems = []
    for name, rows in (("challenge_v3", ch3), ("bert_add_v2", add2)):
        c = collections.Counter(r["utterance"] for r in rows)
        problems += [f"{name} の中で重なる: {u}" for u, k in c.items() if k > 1]
        problems += [f"{name}: {MAX_CHARS} 文字超 {r['utterance']}" for r in rows if len(r["utterance"]) > MAX_CHARS]
    # 確かめ 1: 評価セット v3 が、学習（1,101 行・BERT に足す行）・評価セット v1・v2 と同じ文でない／学習と似すぎていない
    tr_all = sorted({r["utterance"] for r in train + add1 + add2})
    old_eval = {r["utterance"] for r in ch1 + ch2}
    problems += [f"評価セット v3 が学習と同じ: {r['utterance']}" for r in ch3 if r["utterance"] in set(tr_all)]
    problems += [f"評価セット v3 が v1・v2 と同じ: {r['utterance']}" for r in ch3 if r["utterance"] in old_eval]
    pairs = sorted(((near(a["utterance"], b), a["utterance"], b) for a in ch3 for b in tr_all), reverse=True)
    print("評価セット v3 ↔ 学習（1,101 行＋BERT に足す行）で一番似ている組:")
    for s, a, b in pairs[:8]:
        print(f"  {s:.2f}「{a}」↔「{b}」")
    problems += [f"似すぎ（{s:.2f}）: 評価 v3「{a}」↔ 学習「{b}」" for s, a, b in pairs if s >= NEAR]
    # 確かめ 2: BERT に足す行が、学習・評価セット（v1・v2・v3）と同じ文でない／評価セットと似すぎていない（0.5 以上は不可）
    old_train = {r["utterance"] for r in train + add1}
    problems += [f"BERT に足す行が学習と同じ: {r['utterance']}" for r in add2 if r["utterance"] in old_train]
    ev = sorted({r["utterance"] for r in ch1 + ch2 + ch3})
    problems += [f"BERT に足す行が評価セットと同じ・似すぎ（{near(r['utterance'], x):.2f}）:「{r['utterance']}」↔「{x}」"
                 for r in add2 for x in ev if near(r["utterance"], x) >= 0.5]
    # 確かめ 3: 機能の名前の組が、印どおりか
    head_fn = {r.get("os_function", "").rstrip("2") for r in train if r.get("added") == "train_add_v2" and r.get("add_type") == "OS"} | \
              {r["split_unit"].replace("add_os_", "") for r in train if r.get("added") == "train_add_v1" and r.get("add_type") == "OS"}
    bert_fn = {name for name, _ in OS_BERT}
    for name, _ in H_SEEN:
        if name not in head_fn:
            problems.append(f"H seen の {name}: ヘッドの学習に同じ機能が無い")
    for name, _ in H_NEW_SEEN:
        if name in head_fn or name not in bert_fn:
            problems.append(f"H new_seen の {name}: ヘッドの学習に無く、BERT に足す行にある、になっていない")
    for name, _ in H_UNSEEN:
        if name in head_fn or name in bert_fn:
            problems.append(f"H unseen の {name}: 学習に同じ機能がある")
    if problems:
        raise SystemExit(f"止める（{len(problems)} 件）:\n  " + "\n  ".join(problems))
    CH3.mkdir(parents=True, exist_ok=True)
    BERT_ADD2.mkdir(parents=True, exist_ok=True)
    dump = lambda rs: "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rs)
    (CH3 / "utterances.jsonl").write_text(dump(ch3), encoding="utf-8")
    (BERT_ADD2 / "added.jsonl").write_text(dump(add2), encoding="utf-8")
    c = collections.Counter(r["category"] for r in ch3)
    print(f"評価セット v3: {len(ch3)} 行（" + "・".join(f"{k} {NOTES[k]} {c[k]}" for k in NOTES) + "）")
    hs = collections.Counter(r["os_group"] for r in ch3 if r["category"] == "H")
    print("  機能にない依頼: " + "・".join(f"{k} {v}" for k, v in hs.items()) + " / 対象の機能ごと: "
          + "・".join(f"{k.replace('TOOL_', '')} {v}" for k, v in collections.Counter(r["action"] for r in ch3 if r["category"] in "KN").most_common()))
    users = sum(r["author"] == "user" for r in ch3)
    print(f"  利用者が足した行: {users}" + ("" if users else f"（{USER_ROWS.name} を置くと足される）"))
    print(f"BERT に足す機能にない依頼: {len(add2)} 行（{len(OS_BERT)} 機能 × 3 文）")
    print(f"保存しました: {CH3 / 'utterances.jsonl'}・{BERT_ADD2 / 'added.jsonl'}")


if __name__ == "__main__":
    main()
