def build_challenge() -> list[dict]:
    rows, count = [], collections.Counter()

    def add(cat: str, utt: str, act: str, extra: dict | None = None) -> None:
        rows.append({"id": f"c11_{cat}_{count[cat]:03d}", "category": cat, "category_note": NOTES[cat], "utterance": utt, "history": [],
                     "state": {"motion": "stopped", "permission": "allowed"}, "action": ACT[act], "argmode": None,
                     "trainable": False, "purpose": "challenge_eval", "author": "claude", **(extra or {})})
        count[cat] += 1

    for group, form, items in (("seen", "seen", [(n, None, u) for n, u in H11_SEEN]), ("unseen", "操作", [(n, None, u) for n, u in H11_UNSEEN_OP]), ("unseen", "問い合わせ", H11_UNSEEN_Q)):
        for name, kind, utts in items:
            if len(utts) != 2:
                raise SystemExit(f"H {name}: 2 文で 1 機能（{len(utts)} 文）")
            for u in utts:
                add("H", u, "unk", {"os_function": name, "os_group": group, "os_function_in_train": group == "seen", "os_form": form, **({"os_kind": kind} if kind else {})})
    for cat, table in (("K", K11), ("N", N11)):
        for cls, items in table.items():
            for x in items:
                if isinstance(x, tuple):
                    u, lab = x
                    parse(TOOL[cls], lab)
                    add(cat, u, cls, {"arg_label": lab})
                else:
                    add(cat, x, cls)
    for u in F11:
        add("F", u, "chat")
    for kind, utts in G11.items():
        for u in utts:
            add("G", u, "unk", {"g_kind": kind})
    return rows


