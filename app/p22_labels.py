SETS = (("v5", CH5, V5), ("v6", CH6, V6))


def labeled(name: str, ch, labels: dict) -> list[dict]:
    """評価セットの操作系の対象の行に、正解の引数を付けて返す。付いていない行・余った正解があれば止める"""
    rows = [r for r in read_jsonl(ch / "utterances.jsonl") if r["action"][5:] in WRITE and r["action"].startswith("TOOL_")]
    miss = [r["utterance"] for r in rows if r["utterance"] not in labels]
    extra = sorted(set(labels) - {r["utterance"] for r in rows})
    if miss or extra:
        raise SystemExit(f"{name}: 正解が付いていない行 {miss[:5]}（{len(miss)}）／行に無い正解 {extra[:5]}（{len(extra)}）")
    return [{"id": r["id"], "set": name, "category": r["category"], "tool": r["action"][5:], "utterance": r["utterance"],
             "label": labels[r["utterance"]], "expected": parse(r["action"][5:], labels[r["utterance"]])} for r in rows]


def load_all() -> list[dict]:
    return [x for name, ch, labels in SETS for x in labeled(name, ch, labels)]


def main() -> None:
    rows = load_all()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "expected.jsonl").write_bytes("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows).encode("utf-8"))
    for name, _, _ in SETS:
        sub = [r for r in rows if r["set"] == name]
        by = {t: sum(r["tool"] == t for r in sub) for t in WRITE}
        print(f"評価セット {name}: 正解の引数を付けた行 {len(sub)}（" + "・".join(f"{t} {n}" for t, n in by.items()) + f"）/ 聞き返すのが正解 {sum(r['expected'] == ['ASK'] for r in sub)}")
    print(f"保存しました: {OUT / 'expected.jsonl'}")


if __name__ == "__main__":
    main()
