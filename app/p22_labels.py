# 採点する値。ここに無いもの（zone・target）は見ない
SCORED = {"control_hvac": ("temperature", "fan_level", "mode"), "control_media": ("action", "volume"), "set_navigation": ("action", "destination")}
MEDIA = {"play": "play", "pause": "pause", "next": "next", "prev": "previous", "mute": "mute"}


def parse_one(tool: str, text: str):
    """短い記法 1 つを、引数の辞書（か "ASK"）にする"""
    text = text.strip()
    if text == "ASK":
        return "ASK"
    if tool == "control_hvac":
        out = {}
        for part in text.split(","):
            part = part.strip()
            if part.startswith("t"):
                out["temperature"] = float(part[1:])
            elif part.startswith("f"):
                out["fan_level"] = int(part[1:])
            elif part.startswith("m:"):
                out["mode"] = part[2:]
            else:
                raise ValueError(f"空調の記法が読めない: {text}")
        return out
    if tool == "control_media":
        if text in MEDIA:
            return {"action": MEDIA[text]}
        if text.startswith("v") and text[1:].isdigit():
            return {"action": "volume_set", "volume": int(text[1:])}
        raise ValueError(f"メディアの記法が読めない: {text}")
    if tool == "set_navigation":
        if text in ("cancel", "reroute"):
            return {"action": text}
        if text.startswith("set:"):
            return {"action": "set", "destination": text[4:]}
        if text.startswith("way:"):
            return {"action": "add_waypoint", "destination": text[4:]}
        raise ValueError(f"ナビの記法が読めない: {text}")
    raise ValueError(tool)


def parse(tool: str, label: str) -> list:
    return [parse_one(tool, x) for x in label.split("|")]


def scored(tool: str, values: dict) -> dict:
    """採点する値だけを取り出して、比べられる形にそろえる"""
    out = {}
    for k in SCORED[tool]:
        if k in values and values[k] is not None:
            v = values[k]
            out[k] = float(v) if k == "temperature" else int(v) if k in ("fan_level", "volume") else str(v).strip()
    return out


def match(tool: str, expected: list, complete: bool, values: dict) -> bool:
    """取り出した引数が、正解のどれかと合っているか。引数が足りない（聞き返す）は、正解に ASK があるときだけ合っている"""
    if not complete:
        return "ASK" in expected
    got = scored(tool, values)
    return any(e != "ASK" and scored(tool, e) == got for e in expected)


