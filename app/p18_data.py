def build_challenge() -> list[dict]:
    rows, count = [], collections.Counter()

    def add(cat: str, utt: str, act: str, extra: dict | None = None) -> None:
        rows.append({"id": f"c4_{cat}_{count[cat]:03d}", "category": cat, "category_note": NOTES[cat], "utterance": utt, "history": [],
                     "state": {"motion": "stopped", "permission": "allowed"}, "action": ACT[act], "argmode": None,
                     "trainable": False, "purpose": "challenge_eval", "author": "claude", **(extra or {})})
        count[cat] += 1

    for group, items in (("seen", H4_SEEN), ("unseen", H4_UNSEEN)):
        for name, utts in items:
            if len(utts) != 2:
                raise SystemExit(f"H {name}: 2 文で 1 機能（{len(utts)} 文）")
            for u in utts:
                add("H", u, "unk", {"os_function": name, "os_group": group, "os_function_in_train": group == "seen"})
    for cls, utts in K4.items():
        for u in utts:
            add("K", u, cls)
    for cls, utts in N4.items():
        for u in utts:
            add("N", u, cls)
    for u in F4:
        add("F", u, "chat")
    for kind, utts in G4.items():
        for u in utts:
            add("G", u, "unk", {"g_kind": kind})
    if USER_ROWS.exists():           # 任意: 利用者が足した行（発話<TAB>正解）。正解は 機能なし・不明・雑談・hvac・media・nav・status・manual・poi・minfo・cam
        for line in USER_ROWS.read_text(encoding="utf-8-sig").splitlines():
            if not line.strip() or line.startswith("#"):
                continue
            parts = [x.strip() for x in line.split("\t")]
            if len(parts) < 2 or parts[1] not in USER_LABELS:
                raise SystemExit(f"{USER_ROWS.name}: 読めない行「{line}」（発話<TAB>正解。正解は {'・'.join(USER_LABELS)}）")
            cat, act = USER_LABELS[parts[1]]
            add(cat, parts[0], act, {"author": "user", **({"os_function": "user", "os_group": "user", "os_function_in_train": False} if cat == "H" else {}),
                                     **({"g_kind": "利用者"} if cat == "G" else {})})
    return rows


def build_train() -> tuple[list[dict], list[dict]]:
    """（BERT にだけ使っていた 198 行を、ヘッドの学習用に分け直したもの, 新しい 285 行）"""
    tools = {t["name"]: t for t in json.loads((MULTI_ROOT / "configs" / "tools.json").read_text(encoding="utf-8"))["tools"]}
    carried = []
    for src, shift, kind in ((BERT_ADD1 / "added.jsonl", 0, "TG"), (BERT_ADD2 / "added.jsonl", 3, "OS")):
        units: dict = {}
        for r in read_jsonl(src):
            units.setdefault(r["split_unit"], []).append(r)
        for ui, (unit, rs) in enumerate(units.items()):        # 単位ごとに train・validation・test を決め直す（もとは全部 train）
            for r in rs:
                carried.append({**r, "split": SPLIT_CYCLE[(ui + shift) % 5], "note": TYPE_NOTE[kind], "head_from": "P18"})
    rows = []

    def add(kind: str, unit: str, split: str, utts: list[str], cls: str | None, extra: dict | None = None) -> None:
        if len(utts) != 3:
            raise SystemExit(f"{unit}: 3 文で 1 単位（{len(utts)} 文）")
        for k, u in enumerate(utts):
            if cls is None:
                lab = {"route": "UNKNOWN", "category": None, "effect": None, "tool": None, "action": "UNKNOWN"}
            elif cls == "chat":
                lab = {"route": "CHAT", "category": None, "effect": None, "tool": None, "action": "CHAT"}
            else:
                t = tools[TOOL[cls]]
                lab = {"route": "TOOLCALL", "category": t["category"], "effect": t["effect"], "tool": t["name"], "action": f"TOOL_{t['name']}"}
            rows.append({"id": f"{unit}:{k}", "group": unit, "split_unit": unit, "split": split, "utterance": u, "history": [],
                         "state": {"motion": "stopped", "permission": "allowed"}, "last_tool": None, **lab, "argmode": None,
                         "difficulty": "hard", "confusable": None, "note": TYPE_NOTE[kind],
                         "trainable": cls is not None, "purpose": "classification" if cls is not None else "rejection_eval",
                         "added": "train_add_v3", "add_type": kind, **(extra or {})})

    for ui, (name, utts) in enumerate(OS3):
        add("OS", f"add3_os_{name}", SPLIT_CYCLE[(ui + 1) % 5], utts, None, {"os_function": name})
    for ui, (name, utts) in enumerate(AM3):
        add("AM", f"add3_am_{name}", SPLIT_CYCLE[(ui + 2) % 5], utts, None)
    seen = collections.Counter()
    for kind, name, cls, utts in TG3:                          # クラスごとに 3:1:1 で回す（クラスごとに 1 つずつずらす）
        ci = list(TOOL).index(cls) if cls in TOOL else len(TOOL)
        add(kind, f"add3_{kind.lower()}_{name}", SPLIT_CYCLE[(seen[cls] + ci) % 5], utts, cls)
        seen[cls] += 1
    return carried, rows


def md5_of(p) -> str:
    import hashlib
    return hashlib.md5(p.read_bytes()).hexdigest()


def main() -> None:
    ch4 = build_challenge()
    carried, new = build_train()
    base = read_jsonl(TR2 / "utterances.jsonl")                 # 1,101 行
    ch1, ch2, ch3 = read_jsonl(CH1), read_jsonl(CH2 / "utterances.jsonl"), read_jsonl(CH3 / "utterances.jsonl")
    problems = []
    for name, rows in (("challenge_v4", ch4), ("train_add_v3（新しい行）", new)):
        c = collections.Counter(r["utterance"] for r in rows)
        problems += [f"{name} の中で重なる: {u}" for u, k in c.items() if k > 1]
        problems += [f"{name}: {MAX_CHARS} 文字超 {r['utterance']}" for r in rows if len(r["utterance"]) > MAX_CHARS]
    ids = collections.Counter(r["id"] for r in base + carried + new)
    problems += [f"行 id が重なる: {i}" for i, k in ids.items() if k > 1]
    # 確かめ 1: 評価セット v4 が、学習（1,101 行・引き継ぐ 198 行・新しい 285 行）と同じ文でない／似すぎていない。v1〜v3 と同じ文でない
    old_train = {r["utterance"] for r in base + carried}
    tr_all = sorted(old_train | {r["utterance"] for r in new})
    old_eval = {r["utterance"] for r in ch1 + ch2 + ch3}
    problems += [f"評価セット v4 が学習と同じ: {r['utterance']}" for r in ch4 if r["utterance"] in set(tr_all)]
    problems += [f"評価セット v4 が v1〜v3 と同じ: {r['utterance']}" for r in ch4 if r["utterance"] in old_eval]
    pairs = sorted(((near(a["utterance"], b), a["utterance"], b) for a in ch4 for b in tr_all), reverse=True)
    print("評価セット v4 ↔ 学習（1,584 行）で一番似ている組:")
    for s, a, b in pairs[:8]:
        print(f"  {s:.2f}「{a}」↔「{b}」")
    problems += [f"似すぎ（{s:.2f}）: 評価 v4「{a}」↔ 学習「{b}」" for s, a, b in pairs if s >= NEAR]
    # 確かめ 2: 新しい学習の行が、いまの学習と同じ文でない。評価セット v1〜v3 と同じ文でない／似すぎていない（v4 とは確かめ 1 で見ている）
    problems += [f"新しい行がいまの学習と同じ: {r['utterance']}" for r in new if r["utterance"] in old_train]
    problems += [f"新しい行が評価セット（v1〜v3）と同じ・似すぎ（{near(r['utterance'], x):.2f}）:「{r['utterance']}」↔「{x}」"
                 for r in new for x in sorted(old_eval) if near(r["utterance"], x) >= NEAR]
    # 確かめ 3: 機能の名前の組が、印どおりか（seen = 学習に同じ機能がある／unseen = どの学習にも無い）
    head_fn = {r.get("os_function", "").rstrip("2") for r in base if r.get("added") == "train_add_v2" and r.get("add_type") == "OS"} | \
              {r["split_unit"].replace("add_os_", "") for r in base if r.get("added") == "train_add_v1" and r.get("add_type") == "OS"}
    train_fn = head_fn | {name for name, _ in OS_BERT} | {name for name, _ in OS3}
    for name, _ in H4_SEEN:
        if name not in train_fn:
            problems.append(f"H seen の {name}: 学習に同じ機能が無い")
    for name, _ in H4_UNSEEN:
        if name in train_fn:
            problems.append(f"H unseen の {name}: 学習に同じ機能がある")
    # 確かめ 4: split ごとに、足す行のクラスがそろっている（UNKNOWN と、行き先のある行）
    allr = base + carried + new
    by = collections.Counter((r["split"], r["action"]) for r in carried + new)
    for sp in ("train", "validation", "test"):
        for a in ("UNKNOWN", "TOOL_control_hvac", "TOOL_control_media", "TOOL_get_vehicle_status", "TOOL_search_vehicle_manual"):
            if by[(sp, a)] == 0:
                problems.append(f"split={sp} に {a} の足す行が無い")
    if problems:
        raise SystemExit(f"止める（{len(problems)} 件）:\n  " + "\n  ".join(problems))
    CH4.mkdir(parents=True, exist_ok=True)
    TR3.mkdir(parents=True, exist_ok=True)
    dump = lambda rs: "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rs)
    (CH4 / "utterances.jsonl").write_text(dump(ch4), encoding="utf-8")
    (TR3 / "added.jsonl").write_text(dump(carried + new), encoding="utf-8")
    (TR3 / "utterances.jsonl").write_text(dump(allr), encoding="utf-8")            # 1,101 行はそのまま・同じ並びで先頭に置く
    c = collections.Counter(r["category"] for r in ch4)
    print(f"評価セット v4: {len(ch4)} 行（" + "・".join(f"{k} {NOTES[k]} {c[k]}" for k in NOTES) + f"）/ md5 {md5_of(CH4 / 'utterances.jsonl')}")
    hs = collections.Counter(r["os_group"] for r in ch4 if r["category"] == "H")
    print("  機能にない依頼: " + "・".join(f"{k} {v}" for k, v in hs.items()) + " / 対象の機能ごと: "
          + "・".join(f"{k.replace('TOOL_', '')} {v}" for k, v in collections.Counter(r["action"] for r in ch4 if r["category"] in "KN").most_common()))
    users = sum(r["author"] == "user" for r in ch4)
    print(f"  利用者が足した行: {users}" + ("" if users else f"（{USER_ROWS.name} を置くと足される）"))
    t = collections.Counter(r["add_type"] for r in new)
    print(f"学習に足す行 v3: {len(carried) + len(new)} 行 = BERT にだけ使っていた行 {len(carried)}（対象側の文 {sum(r['add_type'] == 'TG' for r in carried)}・"
          f"機能にない依頼 {sum(r['add_type'] == 'OS' for r in carried)}）＋ 新しい行 {len(new)}（" + "・".join(f"{k} {v}" for k, v in t.items()) + "）")
    print("  新しい行の行き先: " + "・".join(f"{k.replace('TOOL_', '')} {v}" for k, v in collections.Counter(r["action"] for r in new).most_common()))
    print("  split（足す行）: " + "・".join(f"{k} {v}" for k, v in collections.Counter(r["split"] for r in carried + new).most_common()))
    kn = sum(r["trainable"] for r in allr)
    os_n = sum(1 for r in allr if r.get("add_type") == "OS")
    print(f"合わせた学習データ: {len(allr)} 行（1,101 行＋{len(carried) + len(new)} 行）= 行き先のある行 {kn}・UNKNOWN {len(allr) - kn}"
          f"（うち機能にない依頼 {os_n}・意図が不明など {len(allr) - kn - os_n}）")
    print(f"保存しました: {CH4 / 'utterances.jsonl'}・{TR3}（added.jsonl・utterances.jsonl）")


if __name__ == "__main__":
    main()
