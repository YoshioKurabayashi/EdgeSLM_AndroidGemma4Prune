def build_challenge() -> list[dict]:
    rows, count = [], collections.Counter()

    def add(cat: str, utt: str, act: str, extra: dict | None = None) -> None:
        rows.append({"id": f"c7_{cat}_{count[cat]:03d}", "category": cat, "category_note": NOTES[cat], "utterance": utt, "history": [],
                     "state": {"motion": "stopped", "permission": "allowed"}, "action": ACT[act], "argmode": None,
                     "trainable": False, "purpose": "challenge_eval", "author": "claude", **(extra or {})})
        count[cat] += 1

    for group, items in (("seen", H7_SEEN), ("unseen", H7_UNSEEN)):
        for name, utts in items:
            if len(utts) != 2:
                raise SystemExit(f"H {name}: 2 文で 1 機能（{len(utts)} 文）")
            for u in utts:
                add("H", u, "unk", {"os_function": name, "os_group": group, "os_function_in_train": group == "seen"})
    for cat, table in (("K", K7), ("N", N7)):
        for cls, items in table.items():
            for x in items:
                if isinstance(x, tuple):
                    u, lab = x
                    parse(TOOL[cls], lab)          # 記法が読めなければここで止まる
                    add(cat, u, cls, {"arg_label": lab})
                else:
                    add(cat, x, cls)
    for u in F7:
        add("F", u, "chat")
    for kind, utts in G7.items():
        for u in utts:
            add("G", u, "unk", {"g_kind": kind})
    if USER_ROWS.exists():           # 任意: 利用者が足した行（発話<TAB>正解）。操作系の行には正解の引数が無いので、値の採点からは外れる
        for line in USER_ROWS.read_text(encoding="utf-8-sig").splitlines():
            if not line.strip() or line.startswith("#"):
                continue
            parts = [x.strip() for x in line.split("\t")]
            if len(parts) < 2 or parts[1] not in USER_LABELS:
                raise SystemExit(f"{USER_ROWS.name}: 読めない行「{line}」（発話<TAB>正解。正解は {'・'.join(USER_LABELS)}）")
            cat, act = USER_LABELS[parts[1]]
            add(cat, parts[0], act, {"author": "user", **({"os_function": "user", "os_group": "user", "os_function_in_train": False} if cat == "H" else {}),
                                     **({"g_kind": "利用者"} if cat == "G" else {})})
    return rows


def labeled(rows: list[dict] | None = None) -> list[dict]:
    """評価セット v7 の、正解の引数が付いた行（`p22_labels.load_all` と同じ形。値まで見た KPI に使う）"""
    rows = rows if rows is not None else read_jsonl(CH7 / "utterances.jsonl")
    out = []
    for r in rows:
        if "arg_label" in r:
            t = r["action"][5:]
            out.append({"id": r["id"], "set": "v7", "category": r["category"], "tool": t, "utterance": r["utterance"], "label": r["arg_label"], "expected": parse(t, r["arg_label"])})
    return out


