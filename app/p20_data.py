def build_challenge() -> list[dict]:
    rows, count = [], collections.Counter()

    def add(cat: str, utt: str, act: str, extra: dict | None = None) -> None:
        rows.append({"id": f"c5_{cat}_{count[cat]:03d}", "category": cat, "category_note": NOTES[cat], "utterance": utt, "history": [],
                     "state": {"motion": "stopped", "permission": "allowed"}, "action": ACT[act], "argmode": None,
                     "trainable": False, "purpose": "challenge_eval", "author": "claude", **(extra or {})})
        count[cat] += 1

    for group, items in (("seen", H5_SEEN), ("unseen", H5_UNSEEN)):
        for name, utts in items:
            if len(utts) != 2:
                raise SystemExit(f"H {name}: 2 文で 1 機能（{len(utts)} 文）")
            for u in utts:
                add("H", u, "unk", {"os_function": name, "os_group": group, "os_function_in_train": group == "seen"})
    for cls, utts in K5.items():
        for u in utts:
            add("K", u, cls)
    for cls, utts in N5.items():
        for u in utts:
            add("N", u, cls)
    for u in F5:
        add("F", u, "chat")
    for kind, utts in G5.items():
        for u in utts:
            add("G", u, "unk", {"g_kind": kind})
    if USER_ROWS.exists():           # 任意: 利用者が足した行（発話<TAB>正解）。正解は 機能なし・不明・雑談・hvac・media・nav・status・manual・poi・minfo・cam
        for line in USER_ROWS.read_text(encoding="utf-8-sig").splitlines():
            if not line.strip() or line.startswith("#"):
                continue
            parts = [x.strip() for x in line.split("\t")]
            if len(parts) < 2 or parts[1] not in USER_LABELS:
                raise SystemExit(f"{USER_ROWS.name}: 読めない行「{line}」（発話<TAB>正解。正解は {'・'.join(USER_LABELS)}）")
            cat, act = USER_LABELS[parts[1]]
            add(cat, parts[0], act, {"author": "user", **({"os_function": "user", "os_group": "user", "os_function_in_train": False} if cat == "H" else {}),
                                     **({"g_kind": "利用者"} if cat == "G" else {})})
    return rows


def main() -> None:
    ch5 = build_challenge()
    own = [r for r in ch5 if r["author"] == "claude"]            # 重なりの確かめは、Claude が書いた行だけ（利用者の行はそのまま使う）
    train = read_jsonl(TR3 / "utterances.jsonl")                 # 1,584 行（BERT の学習に使う行も、すべてこの中にある）
    old = {"v1": read_jsonl(CH1), "v2": read_jsonl(CH2 / "utterances.jsonl"), "v3": read_jsonl(CH3 / "utterances.jsonl"), "v4": read_jsonl(CH4 / "utterances.jsonl")}
    problems = []
    c = collections.Counter(r["utterance"] for r in ch5)
    problems += [f"評価セット v5 の中で重なる: {u}" for u, k in c.items() if k > 1]
    problems += [f"{MAX_CHARS} 文字超: {r['utterance']}" for r in ch5 if len(r["utterance"]) > MAX_CHARS]
    # 確かめ 1: 学習（1,584 行）と同じ文でない／似すぎていない
    tr_all = sorted({r["utterance"] for r in train})
    problems += [f"学習と同じ: {r['utterance']}" for r in own if r["utterance"] in set(tr_all)]
    pairs = sorted(((near(a["utterance"], b), a["utterance"], b) for a in own for b in tr_all), reverse=True)
    print("評価セット v5 ↔ 学習（1,584 行）で一番似ている組:")
    for s, a, b in pairs[:6]:
        print(f"  {s:.2f}「{a}」↔「{b}」")
    problems += [f"学習と似すぎ（{s:.2f}）:「{a}」↔「{b}」" for s, a, b in pairs if s >= NEAR and a != b]
    # 確かめ 2: これまでの評価セット（v1〜v4）と同じ文でない／似すぎていない
    for name, rows in old.items():
        us = sorted({r["utterance"] for r in rows})
        problems += [f"評価セット {name} と同じ: {r['utterance']}" for r in own if r["utterance"] in set(us)]
        problems += [f"評価セット {name} と似すぎ（{near(r['utterance'], x):.2f}）:「{r['utterance']}」↔「{x}」"
                     for r in own for x in us if r["utterance"] != x and near(r["utterance"], x) >= NEAR_OLD]
    # 確かめ 3: 機能の名前（seen = 学習に同じ機能がある／unseen = 学習にも、これまでの評価セットの機能にない依頼にも無い）
    head_fn = {r.get("os_function", "").rstrip("2") for r in train if r.get("added") == "train_add_v2" and r.get("add_type") == "OS"} | \
              {r["split_unit"].replace("add_os_", "") for r in train if r.get("added") == "train_add_v1" and r.get("add_type") == "OS"}
    train_fn = head_fn | {name for name, _ in OS_BERT} | {name for name, _ in OS3}
    old_fn = {n for n, _, _ in H2} | {n for lst in (H_SEEN, H_NEW_SEEN, H_UNSEEN, H4_SEEN, H4_UNSEEN) for n, _ in lst}
    for name, _ in H5_SEEN:
        if name not in train_fn:
            problems.append(f"H seen の {name}: 学習に同じ機能が無い")
    for name, _ in H5_UNSEEN:
        if name in train_fn:
            problems.append(f"H unseen の {name}: 学習に同じ機能がある")
        if name in old_fn:
            problems.append(f"H unseen の {name}: これまでの評価セットに同じ名前の機能がある")
    if problems:
        raise SystemExit(f"止める（{len(problems)} 件）:\n  " + "\n  ".join(problems))
    CH5.mkdir(parents=True, exist_ok=True)
    (CH5 / "utterances.jsonl").write_bytes("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in ch5).encode("utf-8"))   # 改行は LF に固定（md5 を PC でも同じにする）
    c = collections.Counter(r["category"] for r in ch5)
    print(f"評価セット v5: {len(ch5)} 行（" + "・".join(f"{k} {NOTES[k]} {c[k]}" for k in NOTES) + f"）/ md5 {md5_of(CH5 / 'utterances.jsonl')}")
    hs = collections.Counter(r["os_group"] for r in ch5 if r["category"] == "H")
    print("  機能にない依頼: " + "・".join(f"{k} {v}" for k, v in hs.items()) + " / 対象の機能ごと: "
          + "・".join(f"{k.replace('TOOL_', '')} {v}" for k, v in collections.Counter(r["action"] for r in ch5 if r["category"] in "KN").most_common()))
    users = sum(r["author"] == "user" for r in ch5)
    print(f"  利用者が足した行: {users}" + ("" if users else f"（{USER_ROWS.name} を置くと足される）"))
    print(f"保存しました: {CH5 / 'utterances.jsonl'}")


if __name__ == "__main__":
    main()
